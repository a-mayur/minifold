use std::io::Write;
use std::net::SocketAddr;
use std::os::unix::fs::OpenOptionsExt;
use std::path::{Path, PathBuf};

use serde::{Deserialize, Serialize};
use uuid::Uuid;

const MIN_TOKEN_LEN: usize = 16;
const TOKENS_FILE: &str = "tokens.toml";
const TOKENS_HEADER: &str = "# Sign-in tokens generated by Minifold on first start.\n\
# Set MINIFOLD_AUTH_TOKEN / MINIFOLD_ADMIN_TOKEN to use your own instead, or delete this file\n\
# and restart to generate new ones.\n\n";

/// Startup configuration from environment variables. Admin-editable values live in `Settings`.
pub struct Config {
    pub auth_token: String,
    pub admin_token: String,
    pub data_dir: PathBuf,
    pub config_dir: PathBuf,
    pub bind: SocketAddr,
}

impl Config {
    pub fn from_env() -> Result<Self, String> {
        let config_dir = PathBuf::from(std::env::var("MINIFOLD_CONFIG_DIR").unwrap_or_else(|_| "/config".into()));
        std::fs::create_dir_all(&config_dir).map_err(|e| format!("cannot create {}: {e}", config_dir.display()))?;
        let (auth_token, admin_token) =
            resolve_tokens(&config_dir, env_token("MINIFOLD_AUTH_TOKEN")?, env_token("MINIFOLD_ADMIN_TOKEN")?)?;

        let bind_raw = std::env::var("MINIFOLD_BIND").unwrap_or_else(|_| "0.0.0.0:8080".into());
        let bind = bind_raw
            .parse()
            .map_err(|_| format!("MINIFOLD_BIND is not a valid address: {bind_raw:?} (expected e.g. 0.0.0.0:8080)"))?;

        Ok(Self {
            auth_token,
            admin_token,
            data_dir: PathBuf::from(std::env::var("MINIFOLD_DATA_DIR").unwrap_or_else(|_| "/data".into())),
            config_dir,
            bind,
        })
    }

    pub fn settings_path(&self) -> PathBuf {
        self.config_dir.join("settings.toml")
    }
}

/// `Some(token)` when the variable is set and not empty (Unraid passes empty fields as unset).
fn env_token(var: &str) -> Result<Option<String>, String> {
    match std::env::var(var) {
        Ok(value) if !value.trim().is_empty() => validate(var, value.trim()).map(Some),
        _ => Ok(None),
    }
}

fn validate(name: &str, value: &str) -> Result<String, String> {
    if value.len() < MIN_TOKEN_LEN {
        return Err(format!("{name} must be at least {MIN_TOKEN_LEN} characters."));
    }
    if !value.chars().all(|c| c.is_ascii_graphic() && c != ';' && c != ',') {
        return Err(format!("{name} may only contain visible ASCII characters, without ';' or ','."));
    }
    Ok(value.to_string())
}

#[derive(Serialize, Deserialize)]
#[serde(deny_unknown_fields)]
struct StoredTokens {
    auth_token: String,
    admin_token: String,
}

/// Tokens set in the environment win; missing ones come from `tokens.toml`, which is created
/// with random tokens on first start.
fn resolve_tokens(dir: &Path, auth: Option<String>, admin: Option<String>) -> Result<(String, String), String> {
    let (auth, admin) = match (auth, admin) {
        (Some(auth), Some(admin)) => (auth, admin),
        (auth, admin) => {
            let stored = stored_tokens(dir)?;
            (auth.unwrap_or(stored.auth_token), admin.unwrap_or(stored.admin_token))
        }
    };
    if auth == admin {
        return Err("The admin token must be different from the access token (MINIFOLD_AUTH_TOKEN).".into());
    }
    Ok((auth, admin))
}

fn stored_tokens(dir: &Path) -> Result<StoredTokens, String> {
    let path = dir.join(TOKENS_FILE);
    let text = match std::fs::read_to_string(&path) {
        Ok(text) => text,
        Err(e) if e.kind() == std::io::ErrorKind::NotFound => return generate_tokens(&path),
        Err(e) => return Err(format!("cannot read {}: {e}", path.display())),
    };
    let stored: StoredTokens = toml::from_str(&text).map_err(|e| format!("{} is invalid: {e}", path.display()))?;
    validate(&format!("auth_token in {}", path.display()), &stored.auth_token)?;
    validate(&format!("admin_token in {}", path.display()), &stored.admin_token)?;
    tracing::info!("using sign-in tokens from {}", path.display());
    Ok(stored)
}

fn generate_tokens(path: &Path) -> Result<StoredTokens, String> {
    let tokens = StoredTokens { auth_token: random_token(), admin_token: random_token() };
    let body = format!("{TOKENS_HEADER}{}", toml::to_string(&tokens).expect("tokens serialize"));
    // create_new: never overwrite tokens someone is already using; 0600: only this user can read them.
    std::fs::OpenOptions::new()
        .write(true)
        .create_new(true)
        .mode(0o600)
        .open(path)
        .and_then(|mut f| f.write_all(body.as_bytes()))
        .map_err(|e| format!("cannot create {}: {e}", path.display()))?;
    tracing::warn!(
        "No tokens were set, so new ones were generated and saved to {} (they are shown only this once):\n\n    \
         Access token: {}\n    Admin token:  {}\n",
        path.display(),
        tokens.auth_token,
        tokens.admin_token
    );
    Ok(tokens)
}

/// 64 hex characters from two random UUIDs (244 random bits from the OS generator).
fn random_token() -> String {
    format!("{}{}", Uuid::new_v4().simple(), Uuid::new_v4().simple())
}

#[cfg(test)]
mod tests {
    use super::*;
    use std::os::unix::fs::PermissionsExt;

    fn temp_dir(name: &str) -> PathBuf {
        let dir = std::env::temp_dir().join(format!("minifold-tokens-{}-{name}", std::process::id()));
        let _ = std::fs::remove_dir_all(&dir);
        std::fs::create_dir_all(&dir).unwrap();
        dir
    }

    #[test]
    fn generates_once_then_reuses() {
        let dir = temp_dir("generate");
        let (auth, admin) = resolve_tokens(&dir, None, None).unwrap();
        assert_eq!((auth.len(), admin.len()), (64, 64));
        assert_ne!(auth, admin);
        let mode = std::fs::metadata(dir.join(TOKENS_FILE)).unwrap().permissions().mode() & 0o777;
        assert_eq!(mode, 0o600, "only the container user may read the tokens");
        assert_eq!(resolve_tokens(&dir, None, None).unwrap(), (auth, admin), "second start reuses them");
    }

    #[test]
    fn environment_wins_over_the_file() {
        let dir = temp_dir("env");
        let (_, stored_admin) = resolve_tokens(&dir, None, None).unwrap();
        let mine = "my-own-access-token-1234".to_string();
        assert_eq!(resolve_tokens(&dir, Some(mine.clone()), None).unwrap(), (mine, stored_admin));
    }

    #[test]
    fn both_from_environment_needs_no_file() {
        let dir = temp_dir("no-file");
        resolve_tokens(&dir, Some("a".repeat(20)), Some("b".repeat(20))).unwrap();
        assert!(!dir.join(TOKENS_FILE).exists());
        assert!(resolve_tokens(&dir, Some("a".repeat(20)), Some("a".repeat(20))).is_err(), "must differ");
    }

    #[test]
    fn rejects_a_broken_tokens_file() {
        let dir = temp_dir("broken");
        std::fs::write(dir.join(TOKENS_FILE), "auth_token = \"short\"\nadmin_token = \"also-short\"\n").unwrap();
        assert!(resolve_tokens(&dir, None, None).unwrap_err().contains("at least 16"));
    }
}
